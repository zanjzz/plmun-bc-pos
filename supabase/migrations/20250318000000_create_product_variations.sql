alter table public.products
  add column if not exists product_type text not null default 'simple'
    check (product_type in ('simple', 'variable')),
  add column if not exists attributes jsonb not null default '[]'::jsonb;

create table if not exists public.product_variations (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  combination_key text not null,
  attributes jsonb not null default '{}'::jsonb,
  sku text not null default '',
  price numeric(12, 2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  image text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, combination_key)
);

create index if not exists product_variations_product_active_idx
  on public.product_variations(product_id, active);
create unique index if not exists product_variations_sku_unique_idx
  on public.product_variations(lower(sku))
  where sku <> '' and active = true;

drop trigger if exists product_variations_set_updated_at on public.product_variations;
create trigger product_variations_set_updated_at
before update on public.product_variations
for each row execute function public.set_updated_at();

alter table public.product_variations enable row level security;

alter table public.order_items
  add column if not exists variation_id bigint references public.product_variations(id) on delete set null,
  add column if not exists variation_label text,
  add column if not exists variation_attributes jsonb not null default '{}'::jsonb;

alter table public.transaction_items
  add column if not exists variation_id bigint references public.product_variations(id) on delete set null,
  add column if not exists variation_label text,
  add column if not exists variation_attributes jsonb not null default '{}'::jsonb;

alter table public.inventory_movements
  add column if not exists variation_id bigint references public.product_variations(id) on delete set null;

insert into public.product_variations (
  product_id,
  combination_key,
  attributes,
  price,
  stock,
  active
)
select
  product.id,
  'size=' || lower(size.value),
  jsonb_build_object('Size', size.value),
  product.price,
  (product.stock / cardinality(product.sizes)) +
    case when size.ordinality <= product.stock % cardinality(product.sizes) then 1 else 0 end,
  true
from public.products product
cross join lateral unnest(product.sizes) with ordinality as size(value, ordinality)
where cardinality(product.sizes) > 0
on conflict (product_id, combination_key) do nothing;

update public.products
set
  product_type = 'variable',
  attributes = jsonb_build_array(
    jsonb_build_object('id', 'size', 'name', 'Size', 'values', to_jsonb(sizes))
  ),
  stock = 0
where cardinality(sizes) > 0;

create or replace function public.reserve_inventory(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  requested record;
  current_stock integer;
  results jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'No inventory items were supplied.';
  end if;

  for requested in
    select
      (value ->> 'productId')::bigint as product_id,
      nullif(value ->> 'variationId', '')::bigint as variation_id,
      sum((value ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items)
    group by 1, 2
    order by 1, 2 nulls first
  loop
    if requested.product_id is null or requested.quantity <= 0 then
      raise exception 'Inventory quantity must be positive.';
    end if;

    current_stock := null;
    if requested.variation_id is not null then
      select variation.stock
      into current_stock
      from public.product_variations variation
      join public.products product on product.id = variation.product_id
      where variation.id = requested.variation_id
        and variation.product_id = requested.product_id
        and variation.active = true
        and product.active = true
        and product.product_type = 'variable'
      for update of variation;
    else
      select product.stock
      into current_stock
      from public.products product
      where product.id = requested.product_id
        and product.active = true
        and product.product_type = 'simple'
      for update;
    end if;

    if current_stock is null or current_stock < requested.quantity then
      raise exception 'Insufficient stock for product %.', requested.product_id;
    end if;

    if requested.variation_id is not null then
      update public.product_variations
      set stock = stock - requested.quantity
      where id = requested.variation_id
      returning stock into current_stock;
    else
      update public.products
      set stock = stock - requested.quantity
      where id = requested.product_id
      returning stock into current_stock;
    end if;

    results := results || jsonb_build_array(
      jsonb_build_object(
        'productId', requested.product_id,
        'variationId', requested.variation_id,
        'stockAfter', current_stock
      )
    );
  end loop;

  return results;
end;
$$;

revoke all on function public.reserve_inventory(jsonb) from public, anon, authenticated;
grant execute on function public.reserve_inventory(jsonb) to service_role;

create or replace function public.restore_inventory(p_items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  requested record;
begin
  for requested in
    select
      (value ->> 'productId')::bigint as product_id,
      nullif(value ->> 'variationId', '')::bigint as variation_id,
      sum((value ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items)
    group by 1, 2
    order by 1, 2 nulls first
  loop
    if requested.variation_id is not null then
      update public.product_variations
      set stock = stock + requested.quantity
      where id = requested.variation_id and product_id = requested.product_id;
    else
      update public.products
      set stock = stock + requested.quantity
      where id = requested.product_id and product_type = 'simple';
    end if;
  end loop;
end;
$$;

revoke all on function public.restore_inventory(jsonb) from public, anon, authenticated;
grant execute on function public.restore_inventory(jsonb) to service_role;
